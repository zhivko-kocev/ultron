# shellcheck shell=bash
# ultron status: swaybar status line (i3bar JSON), one update every 2 s.
# It runs for as long as the session does, so the loop stays in bash builtins: per tick it starts
# only wpctl, plus pgrep (Jocasta boss) and the periodic probes (ollama every 10 s, Tailscale every 30 s).

_blocks=()

_blk() { # _blk NAME TEXT [COLOR]: append one block to _blocks
  local text=${2//\\/\\\\}
  text=${text//\"/\\\"}
  if [[ -n "${3:-}" ]]; then
    _blocks+=("{\"name\":\"$1\",\"full_text\":\"$text\",\"color\":\"$3\"}")
  else
    _blocks+=("{\"name\":\"$1\",\"full_text\":\"$text\"}")
  fi
}

cmd_status() {
  # Bar colours come from the theme (generated by `ultron apply`); Gruvbox when that file is missing.
  local -A col=([MUTED]="#928374" [URGENT]="#fb4934" [ACCENT]="#fabd2f" [OK]="#b8bb26")
  _kv_read "$ULTRON_GEN/colors" col

  local tick=0 first=1 boss="" local_ai="" ai="" ts="" ts_on=0 joc_up=1
  local prev_total=0 prev_idle=0 total idle cpu=0 user nice sys idl iow irq sirq steal _rest
  local key val _unit mem_total mem_avail used10 out vol clock bat cap bstate f line b waiting fresh=()

  printf '{"version":1}\n[\n'
  while :; do
    # Settings and slow probes.
    if ((tick % 15 == 0)); then
      conf_load
      conf_var boss BOSS
      boss=${boss%% *}
      if local_ai_on; then local_ai=yes; else local_ai=no; fi
      ts_on=0
      if have tailscale && systemctl is-enabled -q tailscaled 2>/dev/null; then ts_on=1; fi
      if ((ts_on)); then
        out=$(tailscale status --json 2>/dev/null || true)
        if [[ "$out" =~ \"BackendState\":[[:space:]]*\"Running\" ]]; then ts="TS"; else ts="TS off"; fi
      fi
    fi
    if [[ "$local_ai" == yes ]] && ((tick % 5 == 0)); then
      if out=$(curl -fsS --max-time 1 http://127.0.0.1:11434/api/ps 2>/dev/null); then
        if [[ "$out" =~ \"name\":\"([^\"]+)\" ]]; then ai="AI ${BASH_REMATCH[1]}"; else ai="AI idle"; fi
      else
        ai="AI off"
      fi
    fi
    if [[ "$boss" == jocasta ]] && ((tick % 3 == 0)); then
      if jocasta_running; then joc_up=1; else joc_up=0; fi
    fi

    # CPU from the /proc/stat difference.
    read -r _ user nice sys idl iow irq sirq steal _rest </proc/stat
    total=$((user + nice + sys + idl + iow + irq + sirq + steal))
    idle=$((idl + iow))
    if ((prev_total > 0 && total > prev_total)); then
      cpu=$(((100 * ((total - prev_total) - (idle - prev_idle))) / (total - prev_total)))
    fi
    prev_total=$total prev_idle=$idle

    # RAM used = MemTotal - MemAvailable, in tenths of a GiB.
    mem_total=0 mem_avail=0
    while read -r key val _unit; do
      case $key in
      MemTotal:) mem_total=$val ;;
      MemAvailable:)
        mem_avail=$val
        break
        ;;
      esac
    done </proc/meminfo
    used10=$(((mem_total - mem_avail) * 10 / 1048576))

    # Volume: "Volume: 0.40 [MUTED]".
    vol=""
    if out=$(wpctl get-volume @DEFAULT_AUDIO_SINK@ 2>/dev/null); then
      if [[ "$out" == *MUTED* ]]; then
        vol="VOL muted"
      elif [[ "$out" =~ ([0-9]+)\.([0-9][0-9]) ]]; then
        vol="VOL $((10#${BASH_REMATCH[1]}${BASH_REMATCH[2]}))%"
      fi
    fi

    # Battery (laptops).
    bat="" cap="" bstate=""
    for f in /sys/class/power_supply/BAT*/capacity; do
      if [[ -r "$f" ]]; then
        read -r cap <"$f" || true
        read -r bstate <"${f%/capacity}/status" || true
        break
      fi
    done

    printf -v clock '%(%a %d %b  %H:%M)T' -1

    # The attention queue: one file per waiting window. Workspaces with windows shown but not seen yet.
    waiting=0
    for f in "$R"/attention/*; do
      if [[ -f "$f" ]]; then waiting=$((waiting + 1)); fi
    done
    fresh=()
    if [[ -s "$R/new" ]]; then mapfile -t fresh <"$R/new"; fi

    _blocks=()
    if [[ "$boss" == jocasta ]]; then
      if ((!joc_up)); then
        _blk boss "J ✗" "${col[URGENT]}"
      elif ((waiting)); then
        _blk boss "J ● $waiting need you" "${col[URGENT]}"
      else
        _blk boss "J" "${col[MUTED]}"
      fi
    elif ((waiting)); then
      _blk boss "● $waiting need you" "${col[URGENT]}"
    else
      _blk boss "boss: $boss" "${col[MUTED]}"
    fi
    if ((${#fresh[@]})); then _blk new "new ${fresh[*]}" "${col[ACCENT]}"; fi
    if [[ -e "$R/focus" ]]; then _blk focus "FOCUS" "${col[ACCENT]}"; fi
    if [[ -e "$R/awake" ]]; then _blk awake "AWAKE" "${col[ACCENT]}"; fi
    if [[ -e "$R/recording" ]]; then _blk rec "REC" "${col[URGENT]}"; fi
    if [[ "$local_ai" == yes && -n "$ai" ]]; then
      if [[ "$ai" == "AI off" ]]; then _blk ai "$ai" "${col[MUTED]}"; else _blk ai "$ai"; fi
    fi
    if ((ts_on)); then
      if [[ "$ts" == TS ]]; then _blk ts "$ts" "${col[OK]}"; else _blk ts "$ts" "${col[MUTED]}"; fi
    fi
    if [[ -n "$cap" ]]; then
      bat="BAT $cap%"
      [[ "$bstate" == Charging ]] && bat+=" +"
      if [[ "$bstate" == Discharging ]] && ((cap <= 15)); then _blk bat "$bat" "${col[URGENT]}"; else _blk bat "$bat"; fi
    fi
    _blk cpu "CPU $cpu%"
    _blk ram "RAM $((used10 / 10)).$((used10 % 10))G"
    if [[ -n "$vol" ]]; then _blk vol "$vol"; fi
    _blk clock "$clock"

    line=""
    for b in "${_blocks[@]}"; do line+="${line:+,}$b"; done
    if ((first)); then
      printf '[%s]\n' "$line"
      first=0
    else
      printf ',[%s]\n' "$line"
    fi

    nap 2
    tick=$((tick + 1))
  done
}
